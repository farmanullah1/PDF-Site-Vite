export function toolsByCategory(key: ToolCategoryKey): ToolConfig[] {
  return TOOLS.filter((t) => t.categoryKey === key);
}

export function toolById(id: string): ToolConfig | undefined {
  return TOOLS.find((t) => t.id === id);
}

export function allImplementedTools(): ToolConfig[] {
  return TOOLS.filter((t) => t.status === 'implemented');
}
